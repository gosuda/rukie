package rukgen

import (
	"fmt"
	"go/format"
	"slices"
	"strings"

	jsonv1 "encoding/json"
	jsonv2 "encoding/json/v2"
)

type modelMethod struct {
	Kind   string `json:"kind"`
	Method string `json:"method"`
}

type modelCode struct {
	Code       string `json:"code"`
	ExitStatus int    `json:"exit_status"`
}

type model struct {
	Methods    []modelMethod `json:"methods"`
	ErrorCodes []modelCode   `json:"error_codes"`
}

func loadModel(raw []byte) (model, error) {
	var m model
	if err := jsonv2.Unmarshal(raw, &m, jsonv1.DefaultOptionsV1()); err != nil {
		return model{}, fmt.Errorf("rukgen decode model: %w", err)
	}
	if len(m.Methods) == 0 || len(m.ErrorCodes) == 0 {
		return model{}, fmt.Errorf("rukgen decode model: empty methods or error codes")
	}
	return m, nil
}

func constName(parts []string) string {
	var out strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		out.WriteString(strings.ToUpper(p[:1]))
		out.WriteString(strings.ToLower(p[1:]))
	}
	return out.String()
}

func methodConst(name string) string {
	return constName(strings.Split(name, "."))
}

func codeConst(code string) string {
	return constName(strings.Split(strings.TrimPrefix(code, "E_"), "_"))
}

func kindConst(kind string) string {
	return constName([]string{kind})
}

// Generate renders the closed sets for one model document.
func Generate(raw []byte) (string, string, error) {
	m, err := loadModel(raw)
	if err != nil {
		return "", "", err
	}
	wireSrc, err := buildWire(m)
	if err != nil {
		return "", "", err
	}
	sentinelsSrc, err := buildSentinels(m)
	if err != nil {
		return "", "", err
	}
	return wireSrc, sentinelsSrc, nil
}

func buildWire(m model) (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by rukgen. DO NOT EDIT.\n\npackage wire\n\nvar (\n")
	for _, method := range m.Methods {
		fmt.Fprintf(&out, "// Method%s names the %s method.\n", methodConst(method.Method), method.Method)
		fmt.Fprintf(&out, "Method%s Method = %q\n\n", methodConst(method.Method), method.Method)
	}
	out.WriteString(")\n\n")
	out.WriteString("type MethodKind uint8\n\nconst (\n")
	var kinds []string
	for _, method := range m.Methods {
		if !slices.Contains(kinds, method.Kind) {
			kinds = append(kinds, method.Kind)
		}
	}
	for i, k := range kinds {
		fmt.Fprintf(&out, "Method%s MethodKind = %d\n", kindConst(k), i+1)
	}
	out.WriteString(")\n\n")
	out.WriteString("func (k MethodKind) String() string {\nswitch k {\n")
	for _, k := range kinds {
		fmt.Fprintf(&out, "case Method%s:\nreturn %q\n", kindConst(k), k)
	}
	out.WriteString("default:\nreturn \"unknown\"\n}\n}\n\n")
	out.WriteString("func (m Method) Kind() MethodKind {\nswitch m {\n")
	for _, method := range m.Methods {
		fmt.Fprintf(&out, "case Method%s:\nreturn Method%s\n", methodConst(method.Method), kindConst(method.Kind))
	}
	out.WriteString("default:\nreturn 0\n}\n}\n\n")
	out.WriteString("func AllMethods() []Method {\nreturn []Method{\n")
	for _, method := range m.Methods {
		fmt.Fprintf(&out, "Method%s,\n", methodConst(method.Method))
	}
	out.WriteString("}\n}\n\n")
	out.WriteString("var (\n")
	for _, code := range m.ErrorCodes {
		fmt.Fprintf(&out, "// Code%s names the %s failure.\n", codeConst(code.Code), code.Code)
		fmt.Fprintf(&out, "Code%s Code = %q\n\n", codeConst(code.Code), code.Code)
	}
	out.WriteString(")\n\n")
	out.WriteString("func (c Code) ExitStatus() int {\nswitch c {\n")
	for _, code := range m.ErrorCodes {
		fmt.Fprintf(&out, "case Code%s:\nreturn %d\n", codeConst(code.Code), code.ExitStatus)
	}
	out.WriteString("default:\nreturn 1\n}\n}\n\n")
	out.WriteString("func AllCodes() []Code {\nreturn []Code{\n")
	for _, code := range m.ErrorCodes {
		fmt.Fprintf(&out, "Code%s,\n", codeConst(code.Code))
	}
	out.WriteString("}\n}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return "", fmt.Errorf("rukgen format wire: %w", err)
	}
	return string(formatted), nil
}

func buildSentinels(m model) (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by rukgen. DO NOT EDIT.\n\npackage ruk\n\nimport (\n\"github.com/gosuda/rukie/internal/ruk/wire\"\n)\n\nvar (\n")
	codes := slices.Clone(m.ErrorCodes)
	for _, code := range codes {
		fmt.Fprintf(&out, "Err%s = &Error{Code: wire.Code%s}\n", codeConst(code.Code), codeConst(code.Code))
	}
	out.WriteString(")\n\nfunc sentinelFor(c wire.Code) *Error {\nswitch c {\n")
	for _, code := range codes {
		fmt.Fprintf(&out, "case wire.Code%s:\nreturn Err%s\n", codeConst(code.Code), codeConst(code.Code))
	}
	out.WriteString("default:\nreturn nil\n}\n}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return "", fmt.Errorf("rukgen format sentinels: %w", err)
	}
	return string(formatted), nil
}
