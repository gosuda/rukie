func main() {
	os.Exit(runDocgen(os.Args[1:]))
}

func runDocgen(argv []string) int {
	flags := flag.NewFlagSet("docgen", flag.ContinueOnError)
	out := flags.String("out", "", "output directory (defaults to docs/reference/operations under the module root)")
	check := flags.Bool("check", false, "compare the tree without writing and exit 1 on drift")
	if err := flags.Parse(argv); err != nil {
		return 64
	}
	if flags.NArg() > 0 {
		_, _ = fmt.Fprintln(os.Stderr, "docgen: takes no positional arguments")
		return 64
	}
	root, err := moduleRoot()
	if err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "docgen: "+err.Error())
		return 1
	}
	dir := cmp.Or(*out, filepath.Join(root, "docs", "reference", "operations"))
	generated, err := renderAll()
	if err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "docgen: "+err.Error())
		return 1
	}
	if *check {
		if err := checkClean(dir, generated); err != nil {
			_, _ = fmt.Fprintln(os.Stderr, "docgen: "+err.Error())
			return 1
		}
		return 0
	}
	if err := writeAll(dir, generated); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "docgen: "+err.Error())
		return 1
	}
	return 0
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("moduleRoot: %w", err)
	}
	for {
		if info, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil && !info.IsDir() {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("moduleRoot: go.mod not found above the working directory")
		}
		dir = parent
	}
}

func buildDocTable(dbPath string) (*op.Table, *op.Document, error) {
	ctx := context.Background()
	st, err := store.Open(ctx, store.Options{Path: dbPath})
	if err != nil {
		return nil, nil, fmt.Errorf("buildDocTable: %w", err)
	}
	defer func() {
		_ = st.Close(context.Background())
	}()
	svc := auth.New(st)
	deps := api.Deps{Service: svc, Limiter: access.NewLimiter(), Reveals: auth.NewRevealCache(), Store: st}
	table := op.NewTable()
	docs := &api.DocStore{}
	for _, step := range []func() error{
		func() error { return api.RegisterAll(table, docs) },
		func() error { return api.RegisterAuth(table, deps) },
		func() error { return api.RegisterUser(table, deps) },
		func() error { return api.RegisterAdmin(table, deps) },
		func() error { return api.RegisterF12(table, deps) },
		func() error { return api.RegisterRepos(table, deps) },
		func() error { return api.RegisterSearch(table, deps) },
		func() error { return api.RegisterCode(table, deps) },
		func() error { return api.RegisterRefs(table, deps) },
		func() error { return api.RegisterOrgs(table, deps) },
	} {
		if serr := step(); serr != nil {
			return nil, nil, fmt.Errorf("buildDocTable: %w", serr)
		}
	}
	fill, err := api.RegisterLLMS(table, "")
	if err != nil {
		return nil, nil, fmt.Errorf("buildDocTable: %w", err)
	}
	views := op.NewViews()
	api.RegisterViews(views)
	api.RegisterAuthViews(views)
	api.RegisterUserViews(views)
	api.RegisterAdminViews(views)
	api.RegisterF12Views(views)
	api.RegisterReposViews(views)
	api.RegisterSearchViews(views)
	api.RegisterCodeViews(views)
	api.RegisterRefsViews(views)
	api.RegisterOrgsViews(views)
	api.RegisterLLMSViews(views)
	key := make([]byte, 32)
	mux := http.NewServeMux()
	server, err := op.Mount(mux, table, op.Config{
		Authenticator: auth.NewAuthenticator(svc),
		IsSiteSegment: api.SiteSegment,
		Idempotency:   op.NewMemoryIdempotency(),
		Audit:         op.FuncAuditor(func(context.Context, op.AuditRow) error { return nil }),
		Limiter:       deps.Limiter,
		CSRFKey:       key,
		Views:         views,
		Title:         "rukie",
		Version:       "0.0.0",
	})
	if err != nil {
		return nil, nil, fmt.Errorf("buildDocTable: %w", err)
	}
	fill(server.Document())
	return table, server.Document(), nil
}

func renderAll() (map[string]string, error) {
	dir, err := os.MkdirTemp("", "docgen-db-*")
	if err != nil {
		return nil, fmt.Errorf("renderAll: %w", err)
	}
	defer func() {
		_ = os.RemoveAll(dir)
	}()
	table, doc, err := buildDocTable(filepath.Join(dir, "docgen.sqlite"))
	if err != nil {
		return nil, err
	}
	return renderReference(table.Specs(), doc), nil
}

func renderReference(specs []op.Spec, doc *op.Document) map[string]string {
	out := make(map[string]string, len(specs)+1)
	var index strings.Builder
	index.WriteString("<!-- generated by tools/docgen: do not edit -->\n\n")
	index.WriteString("# Operation reference\n\n")
	index.WriteString("Every operation in the table. Regenerate with `go run ./tools/docgen`.\n\n")
	index.WriteString("| Operation | Method | Path | Page |\n")
	index.WriteString("| --- | --- | --- | --- |\n")
	for _, s := range specs {
		file := s.Name + ".md"
		index.WriteString("| `" + s.Name + "` | `" + s.Method + "` | `" + s.Path + "` | [" + s.Name + "](./" + file + ") |\n")
		out[file] = renderOp(s, doc)
	}
	out["README.md"] = index.String()
	return out
}

func renderOp(s op.Spec, doc *op.Document) string {
	var b strings.Builder
	b.WriteString("<!-- generated by tools/docgen: do not edit -->\n\n")
	b.WriteString("# `" + s.Name + "`\n\n")
	b.WriteString(s.Summary + "\n")
	if strings.TrimSpace(s.Description) != "" {
		b.WriteString("\n" + strings.TrimSpace(s.Description) + "\n")
	}
	b.WriteString("\n- Method and path: `" + s.Method + " " + s.Path + "`\n")
	b.WriteString("- Scope: `" + s.Scope.String() + "`\n")
	b.WriteString("- Kind: `" + s.Kind.String() + "`\n")
	b.WriteString("- CLI: `" + docCLI(s) + "`\n")
	b.WriteString("- MCP: `" + op.ToolName(s.Name) + "`\n")
	if s.Kind == op.KindMutation {
		b.WriteString("- Idempotency-Key: required on this mutation\n")
	}
	if s.HasETag {
		b.WriteString("- ETag: served; send it back as If-Match to write safely\n")
	}
	if rows := docInputs(s, doc); len(rows) > 0 {
		b.WriteString("\n## Inputs\n\n")
		b.WriteString("| Name | In | Required | Type |\n")
		b.WriteString("| --- | --- | --- | --- |\n")
		for _, r := range rows {
			b.WriteString("| `" + r[0] + "` | " + r[1] + " | " + r[2] + " | `" + r[3] + "` |\n")
		}
	}
	b.WriteString("\n## Errors\n\n")
	slugs := make([]string, 0, len(s.Problems))
	for _, c := range s.Problems {
		slugs = append(slugs, "`"+c.Slug()+"`")
	}
	slices.Sort(slugs)
	line := "Framework problems only."
	if len(slugs) > 0 {
		line = strings.Join(slugs, ", ") + ", plus the framework problems."
	}
	b.WriteString(line + "\n")
	return b.String()
}

func docCLI(s op.Spec) string {
	path := strings.Split(s.Name, ".")
	if len(s.CLI.Path) > 0 {
		path = s.CLI.Path
	}
	return "rukie " + strings.Join(path, " ")
}

func docInputs(s op.Spec, doc *op.Document) [][4]string {
	if doc == nil {
		return nil
	}
	os, ok := doc.Operations[s.Name]
	if !ok {
		return nil
	}
	var rows [][4]string
	for _, p := range os.Params {
		required := "no"
		if p.Required {
			required = "yes"
		}
		rows = append(rows, [4]string{p.Name, p.In, required, docType(p.Schema)})
	}
	props, required := docBody(doc, os.Body)
	for _, name := range slices.Sorted(maps.Keys(props)) {
		need := "no"
		if required[name] {
			need = "yes"
		}
		pm, _ := props[name].(map[string]any)
		rows = append(rows, [4]string{name, "body", need, docType(pm)})
	}
	slices.SortFunc(rows, func(a, b [4]string) int {
		if c := strings.Compare(a[0], b[0]); c != 0 {
			return c
		}
		return strings.Compare(a[1], b[1])
	})
	return rows
}

func docBody(doc *op.Document, body op.Schema) (map[string]any, map[string]bool) {
	if ref, ok := body["$ref"].(string); ok {
		if name, found := strings.CutPrefix(ref, "#/components/schemas/"); found {
			if resolved, ok := doc.Components[name]; ok {
				body = resolved
			}
		}
	}
	props, _ := body["properties"].(map[string]any)
	required := map[string]bool{}
	if req, ok := body["required"].([]any); ok {
		for _, r := range req {
			if name, ok := r.(string); ok {
				required[name] = true
			}
		}
	}
	return props, required
}

func docType(s op.Schema) string {
	if len(s) == 0 {
		return "value"
	}
	if typ, ok := s["type"].(string); ok && typ != "" {
		return typ
	}
	if ref, ok := s["$ref"].(string); ok && ref != "" {
		if _, name, found := strings.CutLast(ref, "/"); found && name != "" {
			return name
		}
		return ref
	}
	return "value"
}

func writeAll(dir string, generated map[string]string) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("writeAll: %w", err)
	}
	current, err := readDir(dir)
	if err != nil {
		return err
	}
	for name := range current {
		if !strings.HasSuffix(name, ".md") {
			continue
		}
		if _, ok := generated[name]; !ok {
			if err := os.Remove(filepath.Join(dir, name)); err != nil {
				return fmt.Errorf("writeAll: %w", err)
			}
		}
	}
	for name, content := range generated {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			return fmt.Errorf("writeAll: %w", err)
		}
	}
	return nil
}

func readDir(dir string) (map[string]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return map[string]string{}, nil
		}
		return nil, fmt.Errorf("readDir: %w", err)
	}
	out := make(map[string]string, len(entries))
	disk := os.DirFS(dir)
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		raw, err := fs.ReadFile(disk, entry.Name())
		if err != nil {
			return nil, fmt.Errorf("readDir: %w", err)
		}
		out[entry.Name()] = string(raw)
	}
	return out, nil
}

func checkClean(dir string, generated map[string]string) error {
	current, err := readDir(dir)
	if err != nil {
		return err
	}
	var drift []string
	for name, content := range generated {
		if current[name] != content {
			drift = append(drift, "changed: "+name)
		}
	}
	for name := range current {
		if _, ok := generated[name]; !ok {
			drift = append(drift, "removed: "+name)
		}
	}
	slices.Sort(drift)
	if len(drift) > 0 {
		return fmt.Errorf("checkClean: reference drift, regenerate with go run ./tools/docgen: %s", strings.Join(drift, ", "))
	}
	return nil
}
