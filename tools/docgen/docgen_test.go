func TestReferenceMatchesTable(t *testing.T) {
	root, err := moduleRoot()
	if err != nil {
		t.Fatalf("module root: %v", err)
	}
	out := filepath.Join(root, "docs", "reference", "operations")
	generated, err := renderAll()
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if len(generated) == 0 {
		t.Fatal("render produced no pages")
	}
	if err := checkClean(out, generated); err != nil {
		t.Fatalf("reference drift: %v", err)
	}
	for name, content := range generated {
		if !strings.HasPrefix(content, "<!-- generated by tools/docgen: do not edit -->") {
			t.Fatalf("%s misses the generated banner", name)
		}
	}
	if _, ok := generated["README.md"]; !ok {
		t.Fatal("reference misses its index")
	}
}

func TestDocgenDetectsTableDrift(t *testing.T) {
	dir := t.TempDir()
	table, doc, err := buildDocTable(filepath.Join(dir, "drift.sqlite"))
	if err != nil {
		t.Fatalf("table: %v", err)
	}
	specs := table.Specs()
	plain := renderReference(specs, doc)
	grown := renderReference(append(specs, op.Spec{
		Name: "api.probe.get", Method: "GET", Path: "/probe",
		Scope: op.ScopePublicRead, Kind: op.KindRead, Summary: "Probe op",
	}), doc)
	if len(grown) != len(plain)+1 {
		t.Fatalf("grown holds %d pages, want %d", len(grown), len(plain)+1)
	}
	if _, ok := grown["api.probe.get.md"]; !ok {
		t.Fatal("grown misses the probe page")
	}
	if plain["README.md"] == grown["README.md"] {
		t.Fatal("the index ignores the table it renders")
	}
}

func TestDocgenCheckFindsDrift(t *testing.T) {
	dir := t.TempDir()
	generated, err := renderAll()
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if err := writeAll(dir, generated); err != nil {
		t.Fatalf("write: %v", err)
	}
	if err := checkClean(dir, generated); err != nil {
		t.Fatalf("exact tree must pass: %v", err)
	}
	mutated := map[string]string{}
	maps.Copy(mutated, generated)
	mutated["README.md"] += "\nchanged\n"
	if err := checkClean(dir, mutated); err == nil {
		t.Fatal("changed bytes must fail the check")
	} else if !strings.Contains(err.Error(), "README.md") {
		t.Fatalf("err = %v, want the changed file", err)
	}
	stray := map[string]string{}
	maps.Copy(stray, generated)
	delete(stray, "README.md")
	if err := checkClean(dir, stray); err == nil {
		t.Fatal("a missing file must fail the check")
	}
}
