func check(t *testing.T, name string, src string) []string {
	t.Helper()
	found, err := violationsInFile(name, []byte(src))
	if err != nil {
		t.Fatalf("%s: unexpected parse error: %v", name, err)
	}
	return found
}

func expectClean(t *testing.T, name string, src string) {
	t.Helper()
	found := check(t, name, src)
	if len(found) != 0 {
		t.Fatalf("%s: expected no violations, got %v", name, found)
	}
}

func expectViolated(t *testing.T, name string, src string, wantLines []int) {
	t.Helper()
	found := check(t, name, src)
	if len(found) != len(wantLines) {
		t.Fatalf("%s: expected %d violations at lines %v, got %v", name, len(wantLines), wantLines, found)
	}
	for i, line := range wantLines {
		want := name + ":" + itoa(line)
		if found[i] != want {
			t.Fatalf("%s: violation %d: expected %s, got %s (all %v)", name, i, want, found[i], found)
		}
	}
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := false
	if n < 0 {
		neg = true
		n = -n
	}
	var digits []byte
	for n > 0 {
		digits = append([]byte{byte('0' + n%10)}, digits...)
		n /= 10
	}
	if neg {
		digits = append([]byte{'-'}, digits...)
	}
	return string(digits)
}

