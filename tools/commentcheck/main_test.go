func TestRevertedExportedRuleStillFlagsUnexported(t *testing.T) {
	allowed := "package foo\n\n// Foo runs one job.\nfunc Foo() {}\n"
	expectClean(t, "foo.go", allowed)
	reverted := strings.Replace(allowed, "func Foo()", "func foo()", 1)
	reverted = strings.Replace(reverted, "// Foo runs one job.", "// foo runs one job.", 1)
	expectViolated(t, "foo.go", reverted, []int{3})
}

func TestRevertedDirectiveRuleStillFlagsText(t *testing.T) {
	expectClean(t, "foo.go", "//go:build linux\n\npackage foo\n")
	expectViolated(t, "foo.go", "//go:build linux\n// dropped\n\npackage foo\n", []int{1})
}
